# Plain Python, run with the Sage environment's python (mpmath at 50 digits).
# Claim: salib's Satterthwaite component intervals equal
#   [σ̂ ν/χ²_{1−α/2}(ν), σ̂ ν/χ²_{α/2}(ν)],  ν = 2σ̂² / Σ_j 2 (c_j MS_j)²/df_j
# (Brennan, Harris & Hanson 1987, ACT RR 87-7, App. A), with χ² quantiles
# computed here from mpmath's regularized incomplete gamma, independent of
# statrs. The mean squares come from the expected-mean-square equations.
# Emits crates/salib-estimators/tests/oracles/g_theory_satterthwaite.rs.
import hashlib, os, struct
import mpmath, sage.version
SALIB = os.environ["SALIB_ROOT"]
mpmath.mp.dps = 50

def chi_quantile(prob, nu):
    """Quantile by bisection on t = ln x, so any depth resolves (no
    small-x approximation is borrowed from the code under test)."""
    cdf = lambda t: mpmath.gammainc(nu / 2, 0, mpmath.exp(t) / 2, regularized=True)
    lo, hi = mpmath.mpf(-1), mpmath.mpf(1)
    while cdf(lo) > prob:
        lo *= 2
    while cdf(hi) < prob:
        hi *= 2
    for _ in range(400):
        mid = (lo + hi) / 2
        if cdf(mid) < prob:
            lo = mid
        else:
            hi = mid
    return mpmath.exp(hi)

def anova_from_data(y, sizes):
    """Exact mean squares of a balanced p×i×r grid from its scores (T terms)."""
    from fractions import Fraction
    import itertools
    np_, ni, nr = sizes
    cells = list(itertools.product(range(np_), range(ni), range(nr)))
    N = len(cells)
    def t(key):
        sums = {}
        for c in cells:
            k = key(c)
            sums[k] = sums.get(k, 0) + Fraction(y[c])
        per = Fraction(N, len(sums))
        return sum(v * v for v in sums.values()) / per
    T = {e: t(f) for e, f in {
        '0': lambda c: 0, 'p': lambda c: c[0], 'i': lambda c: c[1], 'r': lambda c: c[2],
        'pi': lambda c: c[:2], 'pr': lambda c: (c[0], c[2]), 'ir': lambda c: c[1:], 'pir': lambda c: c}.items()}
    ss = {'p': T['p'] - T['0'], 'i': T['i'] - T['0'], 'r': T['r'] - T['0'],
          'pi': T['pi'] - T['p'] - T['i'] + T['0'], 'pr': T['pr'] - T['p'] - T['r'] + T['0'],
          'ir': T['ir'] - T['i'] - T['r'] + T['0'],
          'pir': T['pir'] - T['pi'] - T['pr'] - T['ir'] + T['p'] + T['i'] + T['r'] - T['0']}
    df = {'p': np_ - 1, 'i': ni - 1, 'r': nr - 1, 'pi': (np_ - 1) * (ni - 1), 'pr': (np_ - 1) * (nr - 1),
          'ir': (ni - 1) * (nr - 1), 'pir': (np_ - 1) * (ni - 1) * (nr - 1)}
    return [ss[e] / df[e] for e in ['p', 'i', 'r', 'pi', 'pr', 'ir', 'pir']]

def intervals(c, sizes, alpha, ms=None):
    p, i, r, pi, pr, ir, pir = [mpmath.mpf(float(v)) for v in c]
    np_, ni, nr = [mpmath.mpf(v) for v in sizes]
    if ms is None:
        ms = [pir + nr * pi + ni * pr + ni * nr * p, pir + nr * pi + np_ * ir + np_ * nr * i,
              pir + ni * pr + np_ * ir + np_ * ni * r, pir + nr * pi, pir + ni * pr, pir + np_ * ir, pir]
    else:
        ms = [mpmath.mpf(m.numerator) / m.denominator for m in ms]
    df = [np_ - 1, ni - 1, nr - 1, (np_ - 1) * (ni - 1), (np_ - 1) * (nr - 1), (ni - 1) * (nr - 1),
          (np_ - 1) * (ni - 1) * (nr - 1)]
    terms = [([0, 3, 4, 6], ni * nr), ([1, 3, 5, 6], np_ * nr), ([2, 4, 5, 6], np_ * ni),
             ([3, 6], nr), ([4, 6], ni), ([5, 6], np_), ([6], 1)]
    a = mpmath.mpf(float(alpha))
    out = []
    for k, (used, d) in enumerate(terms):
        est = [p, i, r, pi, pr, ir, pir][k]
        var = sum(2 * (ms[j] / d) ** 2 / df[j] for j in used)
        if est <= 0:
            out.append(None)
            continue
        nu = 2 * est ** 2 / var
        out.append((est * nu / chi_quantile(1 - a / 2, nu), est * nu / chi_quantile(a / 2, nu)))
    return out

def bits(x):
    return "f64::from_bits(0x%016x)" % struct.unpack('<Q', struct.pack('<d', float(x)))[0]

