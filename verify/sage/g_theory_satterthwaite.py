# Plain Python, run with the Sage environment's python (mpmath at 50 digits).
# Claim: salib's Satterthwaite component intervals equal
#   [σ̂ ν/χ²_{1−α/2}(ν), σ̂ ν/χ²_{α/2}(ν)],  ν = 2σ̂² / Σ_j 2 (c_j MS_j)²/df_j
# (Brennan, Harris & Hanson 1987, ACT RR 87-7, App. A), with χ² quantiles
# computed here from mpmath's regularized incomplete gamma, independent of
# statrs. The mean squares come from the expected-mean-square equations.
# Emits crates/salib-estimators/tests/oracles/g_theory_satterthwaite.rs.
import hashlib, os, struct
import mpmath, sage.version
SALIB = os.environ["SALIB_ROOT"]
mpmath.mp.dps = 50

def chi_quantile(prob, nu):
    cdf = lambda x: mpmath.gammainc(nu / 2, 0, x / 2, regularized=True)
    lo, hi = mpmath.mpf(0), mpmath.mpf(1)
    while cdf(hi) < prob:
        lo, hi = hi, hi * 2
    for _ in range(4000):                      # enough to resolve tiny quantiles
        mid = (lo + hi) / 2
        if cdf(mid) < prob:
            lo = mid
        else:
            hi = mid
    return hi

def intervals(c, sizes, alpha):
    p, i, r, pi, pr, ir, pir = [mpmath.mpf(float(v)) for v in c]
    np_, ni, nr = [mpmath.mpf(v) for v in sizes]
    ms = [pir + nr * pi + ni * pr + ni * nr * p, pir + nr * pi + np_ * ir + np_ * nr * i,
          pir + ni * pr + np_ * ir + np_ * ni * r, pir + nr * pi, pir + ni * pr, pir + np_ * ir, pir]
    df = [np_ - 1, ni - 1, nr - 1, (np_ - 1) * (ni - 1), (np_ - 1) * (nr - 1), (ni - 1) * (nr - 1),
          (np_ - 1) * (ni - 1) * (nr - 1)]
    terms = [([0, 3, 4, 6], ni * nr), ([1, 3, 5, 6], np_ * nr), ([2, 4, 5, 6], np_ * ni),
             ([3, 6], nr), ([4, 6], ni), ([5, 6], np_), ([6], 1)]
    a = mpmath.mpf(float(alpha))
    out = []
    for k, (used, d) in enumerate(terms):
        est = [p, i, r, pi, pr, ir, pir][k]
        var = sum(2 * (ms[j] / d) ** 2 / df[j] for j in used)
        if est <= 0:
            out.append(None)
            continue
        nu = 2 * est ** 2 / var
        out.append((est * nu / chi_quantile(1 - a / 2, nu), est * nu / chi_quantile(a / 2, nu)))
    return out

def bits(x):
    return "f64::from_bits(0x%016x)" % struct.unpack('<Q', struct.pack('<d', float(x)))[0]

CASES = [
    ((0.5528, 0.4417, 0.0074, 0.575, 0.1009, 0.1565, 0.9352), (10, 4, 2), 0.05),  # Brennan Synthetic No. 3
    ((4.0, 0.5, 0.5, 0.5, 0.5, 0.5, 0.5), (50, 8, 5), 0.05),
    ((1.0, 1.0, 0.01, 1.0, 0.01, 0.01, 1.0), (20, 5, 2), 0.1),   # tiny nu: deep lower quantiles
    ((1.0, -0.2, 1.0, 1.0, 1.0, -0.1, 1.0), (30, 6, 3), 0.05),   # negative estimates: no interval
]
lines = [
    "// @generated by verify/sage/g_theory_satterthwaite.py — do not edit.",
    "// sha256(script) = %s; SageMath %s" % (hashlib.sha256(open(os.path.join(SALIB, "verify", "sage", "g_theory_satterthwaite.py"), "rb").read()).hexdigest(), sage.version.version),
    "// χ² quantiles by bisection on mpmath's regularized incomplete gamma, 50 digits.",
    "",
    "/// Components, counts, alpha and the exact interval per component (None: no interval).",
    "pub struct SatterthwaiteCase {",
    "    pub components: [f64; 7],",
    "    pub sizes: [usize; 3],",
    "    pub alpha: f64,",
    "    pub intervals: [Option<(f64, f64)>; 7],",
    "}",
    "",
    "pub const SATTERTHWAITE_CASES: &[SatterthwaiteCase] = &[",
]
for c, sizes, alpha in CASES:
    iv = intervals(c, sizes, alpha)
    lines += ["    SatterthwaiteCase {",
              "        components: [%s]," % ", ".join(repr(float(v)) for v in c),
              "        sizes: [%d, %d, %d]," % sizes,
              "        alpha: %r," % alpha,
              "        intervals: [%s]," % ", ".join("None" if v is None else "Some((%s, %s))" % (bits(v[0]), bits(v[1])) for v in iv),
              "    },"]
lines.append("];")
open(os.path.join(SALIB, "crates", "salib-estimators", "tests", "oracles", "g_theory_satterthwaite.rs"), "w").write("\n".join(lines) + "\n")
print("ok: wrote %d Satterthwaite cases" % len(CASES))
